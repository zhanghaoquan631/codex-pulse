import { access, rename, writeFile } from 'node:fs/promises';
import console from 'node:console';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';

// Workspace packages expose their TS sources to the type checker, so the
// compiler's root includes the repository. Keep the established Node/package
// entrypoints stable instead of accidentally starting an older flat output.
const dist = new URL('../dist/', import.meta.url);
const entrypoints = ['index', 'api', 'local-capture-server'];
for (const name of entrypoints) {
  await access(new URL(`services/social-connectors/src/${name}.js`, dist));
  await access(new URL(`services/social-connectors/src/${name}.d.ts`, dist));
}
for (const name of entrypoints) {
  const source = `// Generated by scripts/write-build-entrypoints.mjs; do not edit.\nexport * from './services/social-connectors/src/${name}.js';\n`;
  for (const extension of ['js', 'd.ts']) {
    const destination = new URL(`${name}.${extension}`, dist);
    const temporary = `${fileURLToPath(destination)}.${process.pid}.tmp`;
    await writeFile(temporary, source, 'utf8');
    await rename(temporary, destination);
  }
}
console.log('Updated stable social-connectors build entrypoints.');
